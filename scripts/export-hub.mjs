/**
 * Ships the hub build (dist-hub/, built with --mode hub) into the Baby Mo app:
 *   babymo-app/www/time-adventure/        ← the game
 *   babymo-app/www/icons/games/time-adventure.svg
 * and updates babymo-app/www/sw.js as the hub's CLAUDE.md requires:
 *   - every shipped file is listed in SHELL (between the time-adventure markers)
 *   - the cache version babymo-games-vNNN is bumped so phones refetch
 * Usage: npm run build:hub   (BABYMO_APP=/path/to/babymo-app to override ../babymo-app)
 */
import { cpSync, existsSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync, copyFileSync } from "fs";
import { join, relative, resolve } from "path";

const APP = resolve(process.env.BABYMO_APP || "../babymo-app");
const WWW = join(APP, "www");
if (!existsSync(join(WWW, "sw.js"))) throw new Error("babymo-app not found at " + APP);
const SRC = "dist-hub";
const DEST = join(WWW, "time-adventure");

rmSync(DEST, { recursive: true, force: true });
cpSync(SRC, DEST, { recursive: true });
rmSync(join(DEST, "icons", "icon-1024.png"), { force: true });
// the website serves Time Adventure from /learn/; in the hub it is the folder's own index
// (the hub build only has the learn entry, so "../" in its page and manifest becomes "./")
for (const [from, to, fix] of [["learn/index.html", "index.html", (t) => t.replaceAll('"../', '"./')], ["learn/manifest.webmanifest", "manifest.webmanifest", (t) => t.replaceAll('"../icons/', '"icons/')]]) {
  writeFileSync(join(DEST, to), fix(readFileSync(join(DEST, from), "utf8")));
}
// other games' files that come along with public/ are not part of the hub game
for (const d of ["learn", "rush", "racers"]) rmSync(join(DEST, d), { recursive: true, force: true });
for (const f of readdirSync(join(DEST, "icons"))) if (/^(rush|racers)-/.test(f)) rmSync(join(DEST, "icons", f));
copyFileSync("scripts/hub-icon.svg", join(WWW, "icons", "games", "time-adventure.svg"));

const files = [];
(function walk(d) {
  for (const f of readdirSync(d)) {
    const p = join(d, f);
    if (statSync(p).isDirectory()) walk(p);
    else files.push("/" + relative(WWW, p).split("\\").join("/"));
  }
})(DEST);
files.sort();

let sw = readFileSync(join(WWW, "sw.js"), "utf8");
const START = "  // time-adventure:start (generated by moclock/scripts/export-hub.mjs)";
const END = "  // time-adventure:end";
const block = [START, '  "/time-adventure/",', '  "/icons/games/time-adventure.svg",', ...files.map((f) => `  ${JSON.stringify(f)},`), END].join("\n");
if (sw.includes(START)) {
  sw = sw.slice(0, sw.indexOf(START)) + block + sw.slice(sw.indexOf(END) + END.length);
} else {
  sw = sw.replace(/const SHELL = \[\n/, (m) => m + block + "\n");
}
sw = sw.replace(/babymo-games-v(\d+)/, (_, n) => "babymo-games-v" + (+n + 1));
writeFileSync(join(WWW, "sw.js"), sw);
console.log(`exported ${files.length} files to ${DEST}; ${sw.match(/babymo-games-v\d+/)[0]}`);
