/**
 * Writes <dist>/sw.js: precaches the whole built app (shell, code, fonts,
 * icons, character art) under a cache name derived from the file contents, so
 * every new build gets a new cache and old ones are deleted on activate.
 *   - navigations: network-first (fresh when online), cached shell offline
 *   - everything else: cache-first (files are hashed or versioned), filled at runtime
 *   - the page asks a waiting worker to take over (SKIP_WAITING) when the user taps "Update"
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from "fs";
import { join, relative } from "path";
import { createHash } from "crypto";

const dist = process.argv[2] || "dist";
const files = [];
(function walk(d) {
  for (const f of readdirSync(d)) {
    const p = join(d, f);
    if (statSync(p).isDirectory()) walk(p);
    else files.push(p);
  }
})(dist);
const list = files
  .map((f) => relative(dist, f).split("\\").join("/"))
  .filter((f) => f !== "sw.js" && !f.endsWith(".map") && f !== "icons/icon-1024.png")
  .sort();
// Site layout: Time Rush is the home page (precached on install), Time Adventure lives in
// learn/ and Time Racers in racers/ (each cached when its page asks, so nobody downloads all three).
const refs = (page) => {
  try {
    const html = readFileSync(join(dist, page), "utf8");
    return [...html.matchAll(/(?:src|href)="(?:\.\.\/|\.\/)(assets\/[^"]+)"/g)].map((m) => m[1]);
  } catch { return []; }
};
const homeRefs = refs("index.html");
const learnRefs = refs("learn/index.html");
const isCore = (f) => f === "index.html" || f === "manifest.webmanifest" || homeRefs.includes(f) || /\.woff2$/.test(f) ||
  f.startsWith("characters/") || f.startsWith("rush/") || (f.startsWith("icons/") && !f.startsWith("icons/racers"));
const core = list.filter(isCore);
const learn = list.filter((f) => !isCore(f) && (f.startsWith("learn/") || learnRefs.includes(f)));
const racers = list.filter((f) => !isCore(f) && !learn.includes(f));
const h = createHash("sha256");
for (const f of list) h.update(f).update(readFileSync(join(dist, f)));
const version = h.digest("hex").slice(0, 12);

const sw = `/* Baby Mo games (Time Rush, Time Adventure, Time Racers) — service worker (generated by scripts/gen-sw.mjs) */
const CACHE = "bmt-${version}";
const PRECACHE = ${JSON.stringify(["./", ...core.map((f) => "./" + f)], null, 0)};
const RACERS = ${JSON.stringify(racers.length ? ["./racers/", ...racers.map((f) => "./" + f)] : [], null, 0)};
const LEARN = ${JSON.stringify(learn.length ? ["./learn/", ...learn.map((f) => "./" + f)] : [], null, 0)};

self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)));
});
self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith("bmt-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});
self.addEventListener("message", (e) => {
  if (e.data && e.data.type === "SKIP_WAITING") self.skipWaiting();
  // the racer page asks for its files (3D engine, shaders) to be kept offline
  if (e.data && e.data.type === "CACHE_RACERS") e.waitUntil(caches.open(CACHE).then((c) => c.addAll(RACERS)).catch(() => {}));
  if (e.data && e.data.type === "CACHE_LEARN") e.waitUntil(caches.open(CACHE).then((c) => c.addAll(LEARN)).catch(() => {}));
});
self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== location.origin) return;
  if (req.mode === "navigate") {
    // each app (Time Rush at ./, Time Adventure at ./learn/, Time Racers at ./racers/) keeps its own offline page
    const key = new URL(url.pathname.endsWith("/") ? url.pathname : url.pathname, url).href;
    e.respondWith(
      fetch(req).then((res) => {
        // only a real page of ours may replace the offline copy (not a captive portal or an error page)
        if (res.ok && res.type === "basic" && (res.headers.get("content-type") || "").includes("text/html")) {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put(key, copy)).catch(() => {});
        }
        return res;
      }).catch(() =>
        caches.match(key, { ignoreSearch: true })
          .then((r) => r || caches.match(url.pathname.includes("/racers/") ? "./racers/index.html" : url.pathname.includes("/learn/") ? "./learn/index.html" : "./index.html", { ignoreSearch: true }))
          .then((r) => r || caches.match("./"))
      )
    );
    return;
  }
  e.respondWith(
    caches.match(req, { ignoreSearch: true }).then((hit) => hit || fetch(req).then((res) => {
      if (res.ok && res.type === "basic") {
        const copy = res.clone();
        caches.open(CACHE).then((c) => c.put(req, copy)).catch(() => {});
      }
      return res;
    }))
  );
});
`;
writeFileSync(join(dist, "sw.js"), sw);
console.log(`sw.js: ${core.length} files precached (+${learn.length} learn, ${racers.length} racer files on demand), cache bmt-${version}`);
